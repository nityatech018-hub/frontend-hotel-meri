export const categoryById = (id, list = CATEGORIES) => {
  if (!id) return list[0];
  const direct = list.find((c) => c.id === id);
  if (direct) return direct;
  if (id === "ac-family") return list.find((c) => c.id === "ac-family-double") || list[0];
  if (id === "ac-premium") return list.find((c) => c.id === "ac-premium-round") || list[0];
  if (id === "non-ac") return list.find((c) => c.id === "non-ac-double") || list[0];
  return list[0];
};

